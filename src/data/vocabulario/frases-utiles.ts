import type { CefrLevel } from '@/types/grammar';

/** Una frase para usar tal cual: inglés, su traducción y, a veces, una nota de uso. */
export interface FraseUtil {
  en: string;
  es: string;
  nota?: string;
}

/** Las frases de una situación (restaurante, aeropuerto…). */
export interface SituacionFrases {
  id: string;
  nombre: string;
  icono: string;
  nivel: CefrLevel;
  frases: FraseUtil[];
}

type Fila = [en: string, es: string, nota?: string];

const situacion = (id: string, nombre: string, icono: string, nivel: CefrLevel, filas: Fila[]): SituacionFrases => ({
  id,
  nombre,
  icono,
  nivel,
  frases: filas.map(([en, es, nota]) => ({ en, es, ...(nota ? { nota } : {}) })),
});

