export type FormaOracion = 'afirmativa' | 'negativa' | 'pregunta';

/** Detecta si la frase es afirmativa, negativa o pregunta. */
export function formaDe(en: string): FormaOracion {
  if (en.trim().endsWith('?')) return 'pregunta';
  if (/n't\b|\bnot\b/i.test(en)) return 'negativa';
  return 'afirmativa';
}
